BASE_DIR = Path.cwd()

PARTIAL_FILE = BASE_DIR / "partial reaading.txt"
FEAR_FILE = BASE_DIR / "fear.json"
POSTCOLONIAL_FILE = BASE_DIR / "postcolonial.json"


# ==========================================================
# 2. LOAD JSON ANNOTATIONS
# ==========================================================

def load_annotations(file_path):

    with open(file_path, "r", encoding="utf-8-sig") as f:
        data = json.load(f)

    if "extraction" not in data:
        raise ValueError(
            f"'extraction' list missing in {file_path.name}"
        )

    return data["extraction"]


fear_annotations = load_annotations(FEAR_FILE)
postcolonial_annotations = load_annotations(POSTCOLONIAL_FILE)


# ==========================================================
# 3. TEXT NORMALISATION
# ==========================================================

def tokenize(text):

    text = text.lower()

    text = (
        text.replace("’", "'")
            .replace("‘", "'")
            .replace("—", " ")
            .replace("-", " ")
    )

    return re.findall(
        r"[a-z0-9]+(?:'[a-z0-9]+)?",
        text
    )


# ==========================================================
# 4. READ PARTIAL READING TEXT
# ==========================================================

def read_sentences(file_path):

    sentences = []

    pattern = re.compile(
        r"^\s*(\d+)\.\s*(.*)$"
    )

    with open(
        file_path,
        "r",
        encoding="utf-8-sig"
    ) as f:

        for line in f:

            line = line.strip()

            if not line:
                continue

            match = pattern.match(line)

            if match:

                number = int(match.group(1))
                text = match.group(2).strip()

                sentences.append({
                    "sentence_number": number,
                    "sentence_text": text
                })

            elif sentences:

                # Join wrapped text to the previous sentence.

                sentences[-1]["sentence_text"] += " " + line

            else:

                raise ValueError(
                    "Text must begin with a numbered sentence."
                )

    if not sentences:
        raise ValueError("No numbered sentences found.")

    numbers = [
        s["sentence_number"] for s in sentences
    ]

    if len(numbers) != len(set(numbers)):
        raise ValueError("Duplicate sentence numbers detected.")

    return sentences


sentences = read_sentences(PARTIAL_FILE)


# ==========================================================
# 5. FIND THEMATIC EXPRESSIONS
# ==========================================================

def find_matches(sentence_tokens, expression_tokens):

    matches = []

    phrase_length = len(expression_tokens)

    if phrase_length == 0:
        return matches

    for i in range(
        len(sentence_tokens) - phrase_length + 1
    ):

        if sentence_tokens[
            i:i + phrase_length
        ] == expression_tokens:

            matches.append(
                (i, i + phrase_length)
            )

    return matches


# ==========================================================
# 6. CALCULATE THEMATIC DENSITY
# ==========================================================

def analyse_theme(
    sentence_tokens,
    annotations
):

    matched_expressions = []
    all_spans = []
    occurrence_count = 0

    for annotation in annotations:

        expression = annotation["lexical_item"]

        expression_tokens = tokenize(expression)

        matches = find_matches(
            sentence_tokens,
            expression_tokens
        )

        if matches:

            matched_expressions.append(expression)

            occurrence_count += len(matches)

            all_spans.extend(matches)

    # Count unique word positions.
    # This prevents overlapping expressions from
    # inflating thematic density.

    thematic_positions = set()

    for start, end in all_spans:

        thematic_positions.update(
            range(start, end)
        )

    thematic_word_count = len(thematic_positions)

    total_words = len(sentence_tokens)

    if total_words > 0:

        density = (
            thematic_word_count / total_words
        ) * 100

    else:

        density = 0

    return {
        "occurrences": occurrence_count,
        "thematic_words": thematic_word_count,
        "density": density,
        "expressions": "; ".join(
            matched_expressions
        )
    }


