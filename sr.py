def tokenize(text):
    """
    Convert text into lowercase tokens.
    Ignore punctuation while preserving apostrophes.
    """
    text = text.replace("’", "'").replace("‘", "'")
    text = text.replace("—", " ")

    return re.findall(
        r"[a-z0-9]+(?:'[a-z0-9]+)?",
        text.lower()
    )


# --------------------------------------------------
# 3. READ THE COMPLETE STORY
# --------------------------------------------------

def read_sentences(file_path):

    sentences = []

    for line in file_path.read_text(
        encoding="utf-8"
    ).splitlines():

        line = line.strip()

        if not line:
            continue

        # Detect numbered sentences
        match = re.match(
            r"^(\d+)\.\s*(.*)$",
            line
        )

        if match:

            number = int(match.group(1))
            sentence = match.group(2).strip()

            sentences.append(
                (number, sentence)
            )

        else:
            # Append continuation lines
            # to the preceding sentence

            if sentences:

                number, previous = sentences[-1]

                sentences[-1] = (
                    number,
                    previous + " " + line
                )

    return sentences


