def find_matches(sentence_tokens, expression_tokens):

    matches = []

    length = len(expression_tokens)

    if not length:
        return matches

    for i in range(
        len(sentence_tokens) - length + 1
    ):

        if sentence_tokens[i:i + length] == expression_tokens:

            matches.append(
                (i, i + length)
            )

    return matches


